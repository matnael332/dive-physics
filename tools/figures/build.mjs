// Builds the anatomy figures used by the page.
//   node tools/figures/build.mjs           writes src/figures/*.art.js, css/figures.css and preview pages
//   node tools/figures/build.mjs --audit   proves the geometry of every figure (exit code 1 on a problem)
// The kit in vendor/anatomy (MIT) does the drawing; see its LICENSE.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { k, auditOrExit } from './parts.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const AUDIT = process.argv.includes('--audit');
const only = process.argv.find((a) => a.startsWith('--only='))?.slice(7);

const FIGURES = ['boyle', 'ear'];

// The site's navy glass instead of the kit's neutral greys; air is the site's cyan, water its blue.
const FIG_CSS = `
.fig.iso{
  --anatomy-page:#04121f;--anatomy-card:#071a2c;--anatomy-text:#a9c3d3;--anatomy-strong:#e8f2f8;--anatomy-muted:#7f9aab;
  --anatomy-paper:#0b1f31;--anatomy-face:#0f2639;--anatomy-top:#12304a;
  --anatomy-shade-0:#08192a;--anatomy-shade-1:#0a1d30;--anatomy-shade-2:#0c2236;--anatomy-shade-3:#0e263c;
  --anatomy-lit-top:#22465f;--anatomy-lit-shade:#183850;
  --anatomy-hi:#cfe6f2;--anatomy-mid:#6b8ca3;--anatomy-lo:#3d5a70;--anatomy-faint:#264257;--anatomy-lit:#ffffff;
  --anatomy-halo:#01070d;--anatomy-halo-opacity:.85;--anatomy-dot:#e8f2f8;
  --anatomy-blue:#4fb6ea;
}
.fig .fig-cut{fill:#22506e;stroke:none}
.fig .fig-void{fill:#030c15;stroke:none}
.fig .fig-water{fill:#1d6fa0;opacity:.3;stroke:none}
.fig .fig-water-deep{fill:#1d6fa0;opacity:.55;stroke:none}
.fig .fig-air{fill:#5ee7ff;opacity:.2;stroke:none}
.fig .fig-fluid{fill:#2a5f80;stroke:none}
.fig .fig-puff{fill:#5ee7ff;stroke:none}
.fig .fig-wire{stroke-width:1.1px}
.fig .fig-balloon>.iso-fill{fill:#123a52}
.fig .fig-balloon>.iso-shade[data-shade="0"]{fill:#133f58;stroke:#133f58}
.fig .fig-balloon>.iso-shade[data-shade="1"]{fill:#185072;stroke:#185072}
.fig .fig-balloon>.iso-shade[data-shade="2"]{fill:#1f668e;stroke:#1f668e}
.fig .fig-balloon>.iso-shade[data-shade="3"]{fill:#2b80a8;stroke:#2b80a8}
.fig .fig-balloon>.iso-top{fill:#2b80a8}
`;

const css = `/* Generated by tools/figures/build.mjs. Kit styles: vendor/anatomy (MIT). */\n${k.ISO_CSS}\n${FIG_CSS}`;

for (const name of FIGURES) {
  if (only && only !== name) continue;
  const mod = await import(`./${name}.mjs`);
  const { svg, data, R, P } = mod.build();
  if (AUDIT) {
    console.log(`\n== ${name}`);
    auditOrExit(R, P);
    continue;
  }
  const art = `// Generated by tools/figures/build.mjs from tools/figures/${name}.mjs. Do not edit.\nexport const SVG = ${JSON.stringify(svg)};\nexport const DATA = ${JSON.stringify(data)};\n`;
  writeFileSync(join(ROOT, 'src', 'figures', `${name}.art.js`), art);
  // a standalone preview for the line check and close-ups (not part of the site)
  mkdirSync(join(ROOT, 'tools', 'figures', 'out'), { recursive: true });
  const preview = `<!doctype html><html><head><meta charset="utf-8"><title>${name}</title><style>${css}
body{margin:0;background:#04121f}.wrap{max-width:${mod.W * 2}px;margin:0 auto;padding:24px}</style></head>
<body><div class="wrap"><div class="fig iso iso-plate">${svg.replace(/ data-style="/g, ' style="')}</div></div></body></html>`;
  writeFileSync(join(ROOT, 'tools', 'figures', 'out', `${name}.html`), preview);
  console.log(`wrote ${name}: ${(art.length / 1024).toFixed(0)} KB, ${R.items.length} items, ${R.solids.length} solids`);
}
if (!AUDIT) {
  writeFileSync(join(ROOT, 'css', 'figures.css'), css);
  console.log('wrote css/figures.css');
}
